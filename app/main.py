"""
FastAPI entrypoint (Module C3).

Mounts the vision / nlp / chatbot routers behind a single app, exposes
Swagger docs at /docs (auto-generated by FastAPI), and adds a simple
/health endpoint for container/orchestrator liveness checks.
"""
import gradio as gr
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app.dashboard import build_dashboard
from app.routers import chatbot, nlp, vision

app = FastAPI(
    title="Smart Retail & Customer Intelligence Platform",
    description=(
        "Face-recognition based returning-customer detection, product image "
        "classification, review/chat sentiment analysis, and a hybrid FAQ "
        "chatbot — served behind one production-style API."
    ),
    version="1.0.0",
)

# Permissive CORS for the demo dashboard / Postman; tighten origins for prod.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(vision.router)
app.include_router(nlp.router)
app.include_router(chatbot.router)


@app.get("/health", tags=["Health"])
async def health():
    """Unauthenticated liveness check — used by Docker/cloud health probes."""
    return {"status": "ok"}


# Gradio dashboard, mounted last so it only catches "/" and its own sub-paths
# (e.g. /config, /queue/*) — every route registered above (including the
# auto-generated /docs, /redoc, /openapi.json) is matched first.
app = gr.mount_gradio_app(app, build_dashboard(), path="/")
